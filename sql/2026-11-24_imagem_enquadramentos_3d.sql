CREATE TABLE IF NOT EXISTS imagem_enquadramentos_3d (
  id INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
  obra_id INT NOT NULL,
  imagem_id INT NULL,
  versao_id INT NOT NULL,
  origem_id INT NULL,
  autor_id INT NOT NULL,
  nome VARCHAR(150) NOT NULL,
  composicao JSON NOT NULL,
  revisao INT UNSIGNED NOT NULL DEFAULT 1,
  chave_criacao CHAR(36) NOT NULL,
  preferido TINYINT NULL,
  preferido_por INT NULL,
  preferido_em DATETIME NULL,
  aprovado TINYINT NULL,
  aprovado_por INT NULL,
  aprovado_em DATETIME NULL,
  captura CHAR(64) NULL,
  criado_em DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  atualizado_em DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  UNIQUE KEY uq_enq_repeticao (autor_id,chave_criacao),
  UNIQUE KEY uq_enq_preferido (imagem_id,versao_id,preferido),
  UNIQUE KEY uq_enq_aprovado (imagem_id,versao_id,aprovado),
  KEY idx_enq_obra_versao (obra_id,versao_id,id),
  FOREIGN KEY (obra_id) REFERENCES obra(idobra),
  FOREIGN KEY (imagem_id) REFERENCES imagens_cliente_obra(idimagens_cliente_obra),
  FOREIGN KEY (versao_id) REFERENCES mapa_modelo_3d_versoes(id),
  FOREIGN KEY (origem_id) REFERENCES imagem_enquadramentos_3d(id) ON DELETE SET NULL,
  FOREIGN KEY (autor_id) REFERENCES colaborador(idcolaborador),
  FOREIGN KEY (preferido_por) REFERENCES colaborador(idcolaborador),
  FOREIGN KEY (aprovado_por) REFERENCES colaborador(idcolaborador)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
