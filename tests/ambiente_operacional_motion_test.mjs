import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
let reduced = false;
const window = {matchMedia:()=>({matches:reduced})};
vm.runInNewContext(fs.readFileSync('assets/js/components/ambiente-operacional-panel.js','utf8'), {window});
const panel = Object.create(window.AmbienteOperacionalPanel.prototype);
let animations = 0, rebuilds = 0;
panel.mode = 'compacto';
panel.contexts = new Map();
panel.render = () => rebuilds++;
panel.body = {scrollTop:137, animate:()=>{animations++;return {cancel(){}};}};
panel.panel = {hidden:false,dataset:{},getBoundingClientRect:()=>({width:580,height:600,left:0,top:0}),animate:()=>{animations++;return {cancel(){}};}};
panel.min = {}; panel.restore = {}; panel.max = {setAttribute(){},getAttribute(){}};
panel.setMode('completo');
assert.equal(rebuilds,0);
assert.equal(panel.body.scrollTop,137);
assert.equal(animations,2);
reduced = true;
panel.setMode('minimizado');
assert.equal(animations,2,'Reduced motion must not start animations.');
assert.equal(panel.panel.dataset.mode,'minimizado');
panel.setMode('completo');
assert.equal(panel.body.scrollTop,137);
console.log('OK: modos sem reconstrução, scroll preservado e reduced motion sem animação.');
const originalInfo = {};
let headerInfo = null, heroInfo = null;
panel.imageInfo = originalInfo;
panel.headerImage = {hidden:true,append:info=>{headerInfo=info;heroInfo=null;}};
panel.imageHero = {insertBefore:info=>{heroInfo=info;headerInfo=null;}};
panel.imageTimeline = {};
panel.setMode('completo');
assert.equal(headerInfo,originalInfo,'Mover o mesmo nó para o header.');
assert.equal(panel.headerImage.hidden,false);
panel.setMode('compacto');
assert.equal(heroInfo,originalInfo,'Restaurar o mesmo nó no corpo.');
assert.equal(panel.headerImage.hidden,true);
assert.equal(rebuilds,0);
