import assert from "node:assert/strict";
import { resolve } from "node:path";
import { pathToFileURL } from "node:url";
import { loadViewerModule } from "./viewer_module_loader.mjs";
const path = process.argv.find(arg => arg.startsWith("--three-module="))?.slice(15);
if (!path) throw new Error("Informe --three-module=CAMINHO/three.module.mjs");
const url = pathToFileURL(resolve(path)).href;
const THREE = await import(url);
const { FloorVisibility, visibleModelBounds } = await loadViewerModule("floor-visibility.js", url);
const { visibleSurface } = await loadViewerModule("measurement-geometry.js", url);
const { SolarRayIndex, solarOpaqueMaterial } = await loadViewerModule("solar-ray-tracer.js", url);
const alphaGlass = new THREE.MeshPhysicalMaterial({ transparent: true, opacity: .16, transmission: 0 });
alphaGlass.userData.viewerGlass = true;
assert.equal(solarOpaqueMaterial(alphaGlass), false, "Vidro alpha não pode virar um bloqueio solar opaco ao desligar transmission.");
assert.equal(solarOpaqueMaterial(new THREE.MeshStandardMaterial({ opacity: 0 })), false, "Opacity zero não participa das sombras.");
for (const scale of [.1, 1, 100]) {
  const root = new THREE.Group(), records = new Map(), material = new THREE.MeshStandardMaterial();
  const floors = [20, 0, 10].map(y => {
    const mesh = new THREE.Mesh(new THREE.BoxGeometry(4*scale, 2*scale, 4*scale), material);
    mesh.position.set(10*scale, y*scale, 0); mesh.castShadow = true; root.add(mesh);
    const floor = { id: "floor-" + y, bounds: new THREE.Box3().setFromObject(mesh, true) };
    records.set(mesh, { floor: floor.id });
    return floor;
  });
  const wall = new THREE.Mesh(new THREE.BoxGeometry(2*scale, 30*scale, 2*scale), material);
  wall.position.y = 10*scale; wall.castShadow = true; root.add(wall);
  const roof = new THREE.Mesh(new THREE.BoxGeometry(scale, scale, scale), material);
  roof.position.y = 30*scale; roof.castShadow = true; root.add(roof);
  const nextSlab = new THREE.Mesh(new THREE.BoxGeometry(4*scale, .25*scale, 4*scale), material);
  nextSlab.position.set(10*scale, (11 + .125 - 1e-6)*scale, 0);
  nextSlab.castShadow = true; root.add(nextSlab);
  const hidden = roof.clone(); hidden.visible = false; root.add(hidden);
  const ceilings = new THREE.Group(); ceilings.name = "Tetos_008"; root.add(ceilings);
  const ceiling = new THREE.Mesh(new THREE.BoxGeometry(scale, scale, scale), material);
  ceiling.position.y = 10*scale; ceilings.add(ceiling);
  const detachedCeiling = ceiling.clone(); detachedCeiling.name = "Obj_teto_001"; root.add(detachedCeiling);
  const originalPositions = wall.geometry.attributes.position.array.slice();
  const visibility = new FloorVisibility(root, floors, records);
  const fullBounds = visibleModelBounds(root);
  const rayIndex = new SolarRayIndex(root);
  const upper = visibility.apply(floors[2]);
  assert.deepEqual([...upper], ["floor-20"], "A ordem geométrica independe da ordem da lista e dos nomes.");
  assert.equal(root.children[0].visible, false);
  assert.equal(root.children[1].visible, true);
  assert.equal(root.children[2].visible, true);
  assert.equal(roof.visible, false);
  assert.equal(nextSlab.visible, false, "Laje que começa na fronteira do corte não deixa uma lâmina opaca acima do pavimento.");
  assert.equal(nextSlab.castShadow, false);
  assert.equal(roof.castShadow, false);
  assert.equal(root.children[0].castShadow, false, "Pavimento superior sai explicitamente do shadow pass.");
  assert.equal(hidden.visible, false);
  assert.equal(ceiling.visible, false, "Tetos fora do grupo do pavimento são ocultados por ancestral.");
  assert.equal(detachedCeiling.visible, false);
  assert.notEqual(wall.material, material);
  assert.equal(wall.material.clipShadows, true);
  const exposedBounds = visibleModelBounds(root);
  assert.ok(exposedBounds.max.y < fullBounds.max.y);
  assert.ok(Math.abs(exposedBounds.max.y - floors[2].bounds.max.y) < scale * .001,
    "Frustum solar usa geometria visível e recortada, sem a altura dos andares ocultos.");
  root.visible = false;
  assert.ok(visibleModelBounds(root).isEmpty(), "Ancestrais invisíveis também são descartados.");
  root.visible = true;
  assert.equal(visibleSurface({object: wall, point: new THREE.Vector3(0, 24*scale, 0)}), false);
  assert.equal(visibleSurface({object: wall, point: new THREE.Vector3(0, 0, 0)}), true);
  assert.equal(visibleSurface({object: roof, point: roof.position}), false);
  const hit = rayIndex.trace(new THREE.Vector3(0, 40*scale, 0), new THREE.Vector3(0,-1,0), 100*scale);
  assert.ok(hit && hit.point.y < 11*scale, "Projeção solar ignora partes superiores recortadas.");
  rayIndex.dispose();
  visibility.apply(floors[0]);
  assert.equal(root.children[0].visible, true, "Trocar para um pavimento superior restaura os inferiores antes de aplicar o novo estado.");
  visibility.restore();
  assert.equal(wall.material, material);
  assert.equal(roof.visible, true);
  assert.equal(nextSlab.visible, true);
  assert.equal(nextSlab.castShadow, true);
  assert.equal(roof.castShadow, true);
  assert.equal(ceiling.visible, true);
  assert.equal(detachedCeiling.visible, true);
  assert.equal(hidden.visible, false);
  assert.deepEqual(wall.geometry.attributes.position.array, originalPositions);
  assert.equal(wall.castShadow, true);
  assert.deepEqual(visibleModelBounds(root), fullBounds, "Voltar ao empreendimento restaura também os limites de iluminação.");
  root.traverse(object => { object.geometry?.dispose(); });
  material.dispose();
}
console.log("OK: ordem vertical, inferiores preservados, superiores ocultos, recortes de contexto, medição, raios solares e restauração sem alterar geometria/material original.");
