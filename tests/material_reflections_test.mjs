import assert from 'node:assert/strict';
import { pathToFileURL } from 'node:url';
import { resolve } from 'node:path';
import { loadViewerModule } from './viewer_module_loader.mjs';
const modulePath = process.argv.find(arg => arg.startsWith('--three-module='))?.slice(15);
if (!modulePath) throw new Error('Informe --three-module=CAMINHO/three.module.js (r180).');
const url = pathToFileURL(resolve(modulePath)).href;
const THREE = await import(url);
const { MaterialReflections } = await loadViewerModule('material-reflections.js', url);
const manager = new MaterialReflections();
const facade = new THREE.MeshStandardMaterial({ roughness: .8 });
const glass = new THREE.MeshPhysicalMaterial({ roughness: .2, transparent: true, opacity: .16, ior: 1.45 });
glass.userData.viewerGlass = true;
const originalCompile = glass.onBeforeCompile;
const metal = new THREE.MeshStandardMaterial({ metalness: 1 });
manager.register(facade); manager.register(glass); manager.register(metal);
assert.equal(manager.materials.size, 2);
const coated = new THREE.MeshPhysicalMaterial({ roughness: .8, clearcoat: 1, clearcoatRoughness: .1 });
const transmissive = new THREE.MeshPhysicalMaterial({ roughness: .5, transmission: .8 });
manager.register(coated); manager.register(transmissive);
assert.equal(manager.materials.size, 4, 'Clearcoat e transmissão devem preservar reflexos mesmo sem nomes reconhecidos.');
const environment = new THREE.Texture();
manager.set(environment, .4);
assert.equal(facade.envMap, null, 'Fachada difusa não pode receber HDRI.');
assert.equal(glass.envMap, environment); assert.equal(metal.envMap, environment);
const shader = { fragmentShader: '#include <envmap_physical_pars_fragment>' };
glass.onBeforeCompile(shader, {});
assert.ok(shader.fragmentShader.includes('FLOW: diffuse GI comes only from LightProbe/Hemisphere'));
assert.ok(!shader.fragmentShader.includes('return PI * envMapColor.rgb * envMapIntensity;'));
assert.ok(shader.fragmentShader.includes('return envMapColor.rgb * envMapIntensity;'), 'Termo especular deve permanecer.');
const clone = glass.clone(); manager.register(clone, glass);
const cloneShader = { fragmentShader: '#include <envmap_physical_pars_fragment>' };
clone.onBeforeCompile(cloneShader, {});
assert.equal(cloneShader.fragmentShader, shader.fragmentShader, 'Clones de seleção/contexto devem continuar sem diffuse IBL.');
manager.setGlassIntensity(.5);
manager.setRotation(35);
assert.ok(Math.abs(glass.envMapRotation.y - 35 * Math.PI / 180) < 1e-10);
assert.equal(facade.envMapRotation.y, 0, 'Rotação do HDRI não pode alterar material difuso.');
assert.equal(glass.envMapIntensity, .2); assert.equal(clone.envMapIntensity, .2);
assert.equal(glass.opacity, .16); assert.equal(glass.roughness, .2); assert.equal(glass.ior, 1.45);
manager.set(null);
assert.equal(glass.envMapRotation.y, 0, 'Rotação original deve ser restaurada ao sair do estudo solar.');
assert.equal(glass.envMap, null);
const nativeShader = { fragmentShader: '#include <envmap_physical_pars_fragment>' };
glass.onBeforeCompile(nativeShader, {});
assert.equal(nativeShader.fragmentShader, '#include <envmap_physical_pars_fragment>');
clone.dispose(); assert.equal(manager.materials.size, 4);
manager.clear(); assert.equal(glass.onBeforeCompile, originalCompile);
assert.equal(manager.materials.size, 0);
assert.equal(THREE.ShaderChunk.envmap_physical_pars_fragment.includes('FLOW:'), false, 'Hook não pode contaminar outros consumidores.');
console.log('OK: fachada sem envMap, HDRI apenas especular, clones seguros, tuning, vidro preservado e restauração sem alterar ShaderChunk global.');
