import assert from 'node:assert/strict';
import { readFileSync, readdirSync, existsSync } from 'node:fs';
import { pathToFileURL } from 'node:url';
import { resolve } from 'node:path';
import { loadViewerModule } from './viewer_module_loader.mjs';
import { nightFactor, ENVIRONMENT_SETTINGS } from '../MapaPavimento/predio-3d/environment-config.mjs';
const modulePath = process.argv.find(arg => arg.startsWith('--three-module='))?.slice(15);
if (!modulePath) throw new Error('Informe --three-module=CAMINHO/three.module.js (r180).');
const threeURL = pathToFileURL(resolve(modulePath)).href;
const THREE = await import(threeURL);
const { NightGlass } = await loadViewerModule('night-glass.js', threeURL);
const { MaterialReflections } = await loadViewerModule('material-reflections.js', threeURL);
const root = new THREE.Group();
const glass = new THREE.MeshPhysicalMaterial({ name: 'vidro', opacity: .16, transparent: true, roughness: .2, ior: 1.45 });
const wall = new THREE.MeshStandardMaterial({ name: 'Parede' });
const hooks = [glass.onBeforeCompile, glass.customProgramCacheKey];
const reflections = new MaterialReflections(); reflections.register(glass); reflections.set(new THREE.Texture(),.18);
for (let i=0;i<4314;i++) root.add(new THREE.Mesh(new THREE.BufferGeometry(), i===0?[wall,glass]:glass));
const effect = new NightGlass(); effect.registerModel(root, 102);
assert.equal(effect.meshes,4314); assert.equal(effect.materials.size,1);
effect.setFactor(nightFactor(-6),0); effect.tick(300);
assert.equal(effect.factor,.5);
const shader = { uniforms: {}, fragmentShader: '#include <envmap_physical_pars_fragment>\n#include <colorspace_fragment>' };
glass.onBeforeCompile(shader,{});
assert.ok(shader.fragmentShader.includes('FLOW: diffuse GI'));
assert.ok(!shader.fragmentShader.includes('gl_FragColor.rgb +='), 'Emissão não pode ser somada após a conversão para sRGB.');
assert.ok(glass.emissive.r>glass.emissive.g);
effect.tick(600); assert.equal(effect.factor,1);
const clone=glass.clone(); reflections.register(clone,glass); effect.register(clone,glass);
assert.equal(clone.emissive.r,glass.emissive.r);
assert.equal(glass.opacity,ENVIRONMENT_SETTINGS.nightGlass.nightOpacity); assert.equal(glass.roughness,.2); assert.equal(glass.ior,1.45);
assert.equal(glass.depthWrite,true); assert.equal(glass.transmission,0);
assert.equal(glass.transparent,true); assert.equal(glass.envMap,reflections.texture);
assert.equal(wall.emissive.getHex(),0);
effect.setFactor(nightFactor(0),600); effect.tick(1200);
assert.equal(glass.emissive.getHex(),0); assert.equal(clone.emissive.getHex(),0); assert.equal(glass.emissiveIntensity,1);
assert.equal(glass.opacity,.16); assert.equal(clone.opacity,.16);
effect.setFactor(1,1200); effect.tick(1800); effect.clear();
assert.equal(glass.emissive.getHex(),0); assert.equal(effect.materials.size,0);
reflections.clear(); assert.equal(glass.onBeforeCompile,hooks[0]); assert.equal(glass.customProgramCacheKey,hooks[1]);
effect.registerModel(root,133); assert.equal(effect.materials.size,0);
const disabled = new NightGlass({...ENVIRONMENT_SETTINGS.nightGlass,enabled:false}); disabled.registerModel(root,102); assert.equal(disabled.materials.size,0);
const dir='uploads/model-3d/obra-102'; const file=existsSync(dir) && readdirSync(dir).find(f=>f.includes('_v0008_'));
if (file) {
const bytes=readFileSync(dir+'/'+file); const glb=JSON.parse(bytes.subarray(20,20+bytes.readUInt32LE(12)).toString());
const materialIndex=glb.materials.findIndex(m=>m.name==='vidro');
assert.equal(glb.meshes.flatMap(m=>m.primitives).filter(p=>p.material===materialIndex).length,4314);
}
console.log('OK: GLB v0008/4314 peças, material compartilhado, multimaterial, transição, clones, PBR/hooks preservados, restauração, limpeza e isolamento por obra.');
