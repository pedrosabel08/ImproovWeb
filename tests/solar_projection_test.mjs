import assert from "node:assert/strict";
import { pathToFileURL } from "node:url";
import { resolve } from "node:path";
import { loadViewerModule } from "./viewer_module_loader.mjs";
import { solarAt, solarDayPositions } from "../MapaPavimento/predio-3d/solar-position.mjs";
const modulePath = process.argv.find(arg => arg.startsWith("--three-module="))?.slice("--three-module=".length);
if (!modulePath) throw new Error("Use --three-module=CAMINHO/three.module.js (Three.js r180).");
const threeURL = pathToFileURL(resolve(modulePath)).href;
const THREE = await import(threeURL);
const { SolarRayIndex, createSolarRayField } = await loadViewerModule("solar-ray-tracer.js", threeURL);
const { SolarProjection } = await loadViewerModule("solar-projection.js", threeURL);
const vector = (x,y,z) => new THREE.Vector3(x,y,z);
const close = (a,b) => assert.ok(Math.abs(a-b)<1e-6, String(a)+" != "+String(b));
const material = new THREE.MeshStandardMaterial({ side: THREE.FrontSide });
const geometry = new THREE.BoxGeometry(2,2,2);
const mesh = (z, mat=material, shape=geometry) => { const object=new THREE.Mesh(shape,mat); object.position.z=z; object.castShadow=true; return object; };
const root = new THREE.Group(), near = mesh(1), far = mesh(-2);
const glassMaterial = new THREE.MeshPhysicalMaterial({ transmission:1 });
const glass = mesh(4, glassMaterial, new THREE.BoxGeometry(2,2,.2));
root.add(far,glass,near);
const index = new SolarRayIndex(root);
const originalMaterial=near.material;
let hit=index.trace(vector(0,0,8), vector(0,0,-1), 20);
assert.equal(hit.object,near); close(hit.point.z,2);
assert.equal(near.material,originalMaterial); assert.equal(far.material,originalMaterial);
assert.equal(material.side,THREE.FrontSide);
near.visible=false;
hit=index.trace(vector(0,0,8),vector(0,0,-1),20);
assert.equal(hit.object,far);
near.visible=true; near.castShadow=false;
assert.equal(index.trace(vector(0,0,8),vector(0,0,-1),20).object,far);
near.castShadow=true;
root.visible=false; assert.equal(index.trace(vector(0,0,8),vector(0,0,-1),20),null); root.visible=true;
const empty=new SolarRayIndex(new THREE.Group());
const ground=new THREE.Box3(vector(-10,0,-10),vector(10,0,10));
const floor=empty.trace(vector(0,5,0),vector(0,-1,0),10,ground);
assert.equal(floor.kind,"ground"); close(floor.point.y,0);
assert.equal(empty.trace(vector(20,5,0),vector(0,-1,0),10,ground),null);
const planeRoot=new THREE.Group(), plane=mesh(1,material,new THREE.PlaneGeometry(4,4));
plane.rotation.y=Math.PI; planeRoot.add(plane);
const planeIndex=new SolarRayIndex(planeRoot);
close(planeIndex.trace(vector(0,0,5),vector(0,0,-1),10).point.z,1);
assert.equal(plane.material,material); assert.equal(material.side,THREE.FrontSide);
const mixedRoot=new THREE.Group(), mixedMaterials=Array.from({length:6},()=>material);
mixedMaterials[4]=glassMaterial;
const mixed=mesh(2.5,mixedMaterials,new THREE.BoxGeometry(2,2,1)); mixedRoot.add(mixed);
const mixedIndex=new SolarRayIndex(mixedRoot);
close(mixedIndex.trace(vector(0,0,8),vector(0,0,-1),20).point.z,2);
assert.equal(mixed.material,mixedMaterials);
const translatedRoot=new THREE.Group(), translated=mesh(1);
translatedRoot.position.set(50,10,-7); translatedRoot.scale.setScalar(2); translatedRoot.add(translated);
const translatedIndex=new SolarRayIndex(translatedRoot);
close(translatedIndex.trace(vector(50,10,10),vector(0,0,-1),30).point.z,-3);
const internalRoot=new THREE.Group(), internal=mesh(0); internalRoot.add(internal);
const internalIndex=new SolarRayIndex(internalRoot);
close(internalIndex.trace(vector(0,0,0),vector(0,0,1),10).distance,1);
// Uma falha no raycast também deve restaurar o material do GLB.
const failingRoot=new THREE.Group(), failing=mesh(0); failingRoot.add(failing);
const failingIndex=new SolarRayIndex(failingRoot);
failing.raycast=()=>{throw new Error("fixture");};
assert.throws(()=>failingIndex.trace(vector(0,0,5),vector(0,0,-1),10),/fixture/);
assert.equal(failing.material,material);
const config={latitude:-27.0992256,longitude:-48.6179817,norte_graus:83.9,timezone:"America/Sao_Paulo"};
const bounds=new THREE.Box3().setFromObject(root,true);
for (const time of ["08:00","12:00","16:00"]) {
 const sun=solarAt(config,"2026-10-13",time), field=createSolarRayField(bounds,sun.direction);
 assert.equal(field.length,25);
 const incoming=vector(sun.direction.x,sun.direction.y,sun.direction.z).negate();
 for(const ray of field) { close(ray.direction.length(),1); close(ray.direction.dot(incoming),1); }
}
assert.deepEqual(createSolarRayField(bounds,{x:0,y:-1,z:0}),[]);
for(const [date,hours] of [["2026-03-08",23],["2026-11-01",25]]) {
 const day=solarDayPositions({...config,timezone:"America/New_York"},date);
 close((day.at(-1).date-day[0].date)/3600000,hours);
 for(let i=1;i<day.length;i++) assert.equal(day[i].date-day[i-1].date,600000);
}
const day=solarDayPositions(config,"2026-10-13");
assert.equal(day.length,145);
const noon=solarAt(config,"2026-10-13","12:00"), noonSample=day.find(s=>s.date.getTime()===noon.date.getTime());
assert.deepEqual(noonSample.direction,noon.direction);
const scene=new THREE.Scene(), states=[];
const projection=new SolarProjection(scene,null,state=>states.push(state));
projection.setModel(root,bounds);
projection.showPath(config,"2026-10-13");
assert.ok(projection.path.visible && projection.path.geometry.drawRange.count>0);
const version=projection.path.geometry.getAttribute("position").version;
projection.showPath(config,"2026-10-13");
assert.equal(projection.path.geometry.getAttribute("position").version,version);
projection.showPath(config,"2026-12-21");
assert.ok(projection.path.geometry.getAttribute("position").version>version);
const footprint=new THREE.Box3(vector(-20,-1.01,-20),vector(20,-1.01,20));
assert.equal(await projection.requestRays(noon.direction,footprint),true);
assert.ok(states.at(-1).rays>0 && states.at(-1).rays<=25);
const earlier=projection.requestRays(solarAt(config,"2026-10-13","08:00").direction,footprint);
const late=solarAt(config,"2026-10-13","16:00");
const latest=projection.requestRays(late.direction,footprint);
assert.deepEqual(await Promise.all([earlier,latest]),[false,true]);
const positions=projection.rays.geometry.getAttribute("position"), incoming=vector(late.direction.x,late.direction.y,late.direction.z).negate();
for(let i=0;i<projection.rays.geometry.drawRange.count;i+=6) {
 const start=new THREE.Vector3().fromBufferAttribute(positions,i), end=new THREE.Vector3().fromBufferAttribute(positions,i+1);
 close(end.sub(start).normalize().dot(incoming),1);
}
const pending=projection.requestRays(noon.direction,footprint);
projection.hide(); assert.equal(await pending,false); assert.equal(projection.rays.visible,false);
projection.showPath({...config,latitude:80},"2026-12-21"); assert.equal(projection.path.visible,false);
projection.setModel(null,null);
assert.equal(await projection.requestRays(noon.direction,footprint),false);
for(const item of [index,empty,planeIndex,mixedIndex,translatedIndex,internalIndex,failingIndex]) item.dispose();
console.log("OK: raios paralelos, primeiro obstáculo, vidro/grupos, faces pelo verso, visibilidade, transformações, restauração de material, cancelamento, trajetória, cache e dias de 23/25h.");
